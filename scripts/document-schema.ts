/** Generates docs/fpl-api-schema.md from the captured bootstrap-static + fixtures snapshot. */
import { readFileSync, writeFileSync } from "node:fs";

const b = JSON.parse(readFileSync("tests/fixtures/bootstrap-static.json", "utf8"));
const f = JSON.parse(readFileSync("tests/fixtures/fixtures.json", "utf8"));

const type = (v: unknown): string => (v === null ? "null" : Array.isArray(v) ? "array" : typeof v);
function table(obj: Record<string, unknown>, mvp: Set<string> = new Set()) {
  const rows = Object.entries(obj).map(([k, v]) => {
    const s = typeof v === "object" && v !== null ? JSON.stringify(v).slice(0, 40) : String(v).slice(0, 40);
    return `| \`${k}\` | ${type(v)} | ${s.replace(/\|/g, "\\|")} | ${mvp.has(k) ? "✅" : ""} |`;
  });
  return ["| Field | Type | Example | Used |", "|---|---|---|---|", ...rows].join("\n");
}

const used = new Set(
  "id code web_name first_name second_name team element_type now_cost total_points points_per_game form selected_by_percent minutes starts goals_scored assists expected_goals expected_assists expected_goal_involvements expected_goals_per_90 expected_assists_per_90 expected_goal_involvements_per_90 clean_sheets goals_conceded expected_goals_conceded saves bonus bps influence creativity threat ict_index defensive_contribution defensive_contribution_per_90 yellow_cards red_cards chance_of_playing_next_round status news penalties_order direct_freekicks_order corners_and_indirect_freekicks_order".split(" "),
);
const md = `# FPL API response schema

> Generated by \`scripts/document-schema.ts\` from a real snapshot (\`tests/fixtures/\`). The API is **unofficial and undocumented**; fields can change without notice, so the app reads it through a normalisation layer (\`lib/fpl/normalizer.ts\`).

## Endpoints

| Endpoint | Purpose | Used for |
|---|---|---|
| \`GET /api/bootstrap-static/\` | Whole-season static data (~1.8 MB) | players, teams, gameweeks, rules, scoring |
| \`GET /api/fixtures/\` | All 380 fixtures (\`?event=N\` for one gameweek) | fixture analysis, FDR, team goals for/against |
| \`GET /api/element-summary/{id}/\` | One player: per-gameweek \`history\`, upcoming \`fixtures\` | player page, consistency, backtest |
| \`GET /api/event/{gw}/live/\` | Live per-player stats for a gameweek | client helper provided (\`getLive\`), not needed for projections |

Responses are plain JSON. During deadline processing the API can answer HTTP 200 with a plain-text "being updated" body, so the client treats a non-JSON body as a failure and falls back to stale data.

## bootstrap-static top-level keys

${Object.entries(b).map(([k, v]) => `- \`${k}\` — ${type(v)}${Array.isArray(v) ? ` (${v.length} items)` : ""}`).join("\n")}

## \`elements\` (players) — ${b.elements.length} items, ${Object.keys(b.elements[0]).length} fields

Fields marked ✅ are consumed by the MVP. Everything else (price-change projections, ranks, ep_next, dreamteam flags…) is ignored.
Numeric values often arrive as **strings** (\`"5.5"\`) — the normaliser parses them. \`now_cost\` is in tenths of £m.

${table(b.elements[0], used)}

### Position codes (\`element_type\`)

${b.element_types.map((t: any) => `- ${t.id} = ${t.singular_name_short} (squad_select ${t.squad_select}, play ${t.squad_min_play}–${t.squad_max_play})`).join("\n")}

### Status codes

\`a\` available · \`d\` doubtful · \`i\` injured · \`s\` suspended · \`u\` unavailable · \`n\` not in squad. \`chance_of_playing_next_round\` is \`null\` (no news) or 0/25/50/75/100.

## \`teams\` — ${b.teams.length} items

${table(b.teams[0])}

> Note: in this snapshot \`strength_attack_*\` / \`strength_defence_*\` are all **0** and \`played/win/draw/loss\` are 0, so the app derives team attack/defence from finished fixtures and player xG/xGC totals rather than trusting these fields.

## \`events\` (gameweeks) — ${b.events.length} items

${table(Object.fromEntries(Object.entries(b.events[0]).filter(([k]) => !["chip_plays", "top_element_info", "overrides"].includes(k))))}

\`is_current\`, \`is_next\`, \`finished\`, \`deadline_time\` drive the gameweek selector and countdown.

## Rules and scoring

The task brief suggests \`game_settings\` holds the scoring rules. In this snapshot:

- \`game_settings\` (and \`game_config.rules\`) holds **squad rules**: \`squad_squadsize=${b.game_settings.squad_squadsize}\`, \`squad_squadplay=${b.game_settings.squad_squadplay}\`, \`squad_team_limit=${b.game_settings.squad_team_limit}\`, \`squad_total_spend=${b.game_settings.squad_total_spend}\` (tenths of £m).
- \`game_config.scoring\` holds the **points table** (goal/assist/clean-sheet/saves/bonus/cards/defensive-contribution values per position).

\`\`\`json
${JSON.stringify(b.game_config.scoring, null, 2).split("\n").slice(0, 28).join("\n")}
  ...
}
\`\`\`

Both are read at runtime; defaults are only used if a key disappears.

## fixtures — ${f.length} items

${table(Object.fromEntries(Object.entries(f.find((x: any) => x.event === 11)).filter(([k]) => k !== "stats")))}

\`team_h_difficulty\` / \`team_a_difficulty\` is FPL's official FDR (1–5) for each side. \`event\` is \`null\` for unscheduled fixtures.

## element-summary \`history\` row (per gameweek per fixture)

\`round, total_points, minutes, starts, goals_scored, assists, clean_sheets, goals_conceded, saves, bonus, bps, expected_goals, expected_assists, expected_goal_involvements, expected_goals_conceded, defensive_contribution, yellow_cards, red_cards, value, selected, was_home, opponent_team …\` — used for point-in-time backtesting and the consistency metric. Double gameweeks produce two rows with the same \`round\`.

## Fields requested in the brief but not provided

| Requested | Reality |
|---|---|
| shots on target, touches in opposition box | Not in bootstrap-static (only ICT \`threat\` is a proxy) |
| opponent xG conceded per team | Not provided per team; derived from the first-choice goalkeeper's \`expected_goals_conceded\` |
| recent starting history | Only season totals in bootstrap; per-gameweek \`starts\` exist in element-summary (used by the player page and backtest) |
| \`game_settings\` scoring | Lives in \`game_config.scoring\` |
`;
writeFileSync("docs/fpl-api-schema.md", md);
console.log("written docs/fpl-api-schema.md", md.length);
